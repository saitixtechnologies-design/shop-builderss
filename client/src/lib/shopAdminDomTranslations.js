const reverseTranslations = new Map();
Object.entries(translations).forEach(([english, [hindi, hinglish]]) => {
    reverseTranslations.set(hindi, english);
    reverseTranslations.set(hinglish, english);
});

const textNodeOrigins = new WeakMap();
const attributeOrigins = new WeakMap();

const normalize = (value) => value.replace(/\s+/g, " ").trim();

const getEnglishSource = (value) => {
    const normalized = normalize(value);
    if (translations[normalized]) return normalized;
    return reverseTranslations.get(normalized) || null;
};

const localized = (english, language) => {
    if (language === "en") return english;
    const translation = translations[english];
    if (!translation) return english;
    return language === "hi" ? translation[0] : translation[1];
};

const translateTextNode = (node, language) => {
    const value = node.nodeValue || "";
    const normalized = normalize(value);
    if (!normalized) return;

    let origin = textNodeOrigins.get(node);
    const currentEnglish = getEnglishSource(value);
    if (!origin || (currentEnglish && currentEnglish !== origin.english)) {
        const english = currentEnglish;
        if (!english) return;
        const leading = value.match(/^\s*/)?.[0] || "";
        const trailing = value.match(/\s*$/)?.[0] || "";
        origin = { english, leading, trailing };
        textNodeOrigins.set(node, origin);
    }

    const translated = `${origin.leading}${localized(origin.english, language)}${origin.trailing}`;
    if (node.nodeValue !== translated) node.nodeValue = translated;
};

const translateAttributes = (element, language) => {
    const attributes = ["placeholder", "title", "aria-label", "aria-description", "alt"];
    let originals = attributeOrigins.get(element);

    attributes.forEach((name) => {
        const current = element.getAttribute(name);
        if (current === null) return;
        if (!originals) {
            originals = {};
            attributeOrigins.set(element, originals);
        }
        const currentEnglish = getEnglishSource(current);
        if (!originals[name] || (currentEnglish && currentEnglish !== originals[name])) {
            if (!currentEnglish) return;
            originals[name] = currentEnglish;
        }
        const translated = localized(originals[name], language);
        if (current !== translated) element.setAttribute(name, translated);
    });
};

export const translateShopAdminTree = (root, language) => {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let textNode = walker.nextNode();
    while (textNode) {
        translateTextNode(textNode, language);
        textNode = walker.nextNode();
    }
    translateAttributes(root, language);
    root.querySelectorAll("*").forEach((element) => translateAttributes(element, language));
};
